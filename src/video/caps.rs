fn name(names: &mut Vec<CString>, text: &str) -> *const c_char {
    names.push(CString::new(text).expect("constant has no NUL"));
    names.last().unwrap().as_ptr()
}
impl NvC2Caps {
    pub fn query(
        mut query: impl FnMut(u32) -> Result<NvVideoCaps, Error>,
        nvenc: impl FnOnce() -> Result<u32, Error>,
    ) -> Result<Self, Error> {
        let mut names = Vec::with_capacity(14);
        let mut decoders = Vec::with_capacity(4);
        let mut x=String::from("<?xml version=\"1.0\" encoding=\"utf-8\" ?>\n<!-- Generated by nvc2-xmlgen from nv_video_query_caps() and the NVENC class on this GPU. Do not edit:\n     regenerate (the service refuses to start when this file and the live caps differ). -->\n<MediaCodecs>\n    <Decoders>\n");
        for (codec, n, m) in DECODERS {
            let c = query(codec)
                .map_err(|(rc, msg)| (rc, format!("nv_video_query_caps({n}) = {rc}: {msg}")))?;
            if c.supported == 0 {
                continue;
            }
            if c.codec != codec
                || c.max_width == 0
                || c.max_height == 0
                || c.min_width > c.max_width
                || c.min_height > c.max_height
                || c.bit_depth_mask & (1 << 8) == 0
            {
                return Err((-8,format!("nv_video_query_caps({n}) reports supported with an unusable size range or without 8-bit")));
            }
            writeln!(x,"        <MediaCodec name=\"{n}\" type=\"{m}\">\n            <Limit name=\"size\" min=\"{}x{}\" max=\"{}x{}\" />\n            <Limit name=\"alignment\" value=\"2x2\" />\n            <Limit name=\"block-size\" value=\"16x16\" />\n            <Feature name=\"adaptive-playback\" />\n        </MediaCodec>",c.min_width.wrapping_add(1)&!1,c.min_height.wrapping_add(1)&!1,c.max_width&!1,c.max_height&!1).unwrap();
            decoders.push(NvC2DecoderCaps {
                codec,
                name: name(&mut names, n),
                mime: name(&mut names, m),
                caps: c,
            });
        }
        let nvenc_class = if decoders.is_empty() { 0 } else { nvenc()? };
        let mut encoders = Vec::with_capacity(3);
        x.push_str("    </Decoders>\n    <Encoders>\n");
        if nvenc_class == 0xc9b7 {
            for (codec, n, m, min_width, min_height, max_width, max_height) in ENCODERS {
                writeln!(x,"        <MediaCodec name=\"{n}\" type=\"{m}\">\n            <Limit name=\"size\" min=\"{min_width}x{min_height}\" max=\"{max_width}x{max_height}\" />\n            <Limit name=\"alignment\" value=\"2x2\" />\n            <Limit name=\"block-size\" value=\"16x16\" />\n            <Limit name=\"bitrate\" range=\"1-200000000\" />\n            <Feature name=\"bitrate-modes\" value=\"VBR,CBR,CQ\" />\n        </MediaCodec>").unwrap();
                encoders.push(NvC2EncoderCaps {
                    codec,
                    name: name(&mut names, n),
                    mime: name(&mut names, m),
                    min_width,
                    min_height,
                    max_width,
                    max_height,
                });
            }
        }
        x.push_str("    </Encoders>\n</MediaCodecs>\n");
        Ok(Self {
            decoders,
            encoders,
            _names: names,
            xml: CString::new(x).unwrap(),
            nvenc_class,
        })
    }
    pub fn view(&self) -> NvC2CapsView {
        NvC2CapsView {
            abi_version: 2,
            nvenc_class: self.nvenc_class,
            decoders: if self.decoders.is_empty() {
                ptr::null()
            } else {
                self.decoders.as_ptr()
            },
            decoder_count: self.decoders.len() as u32,
            encoders: if self.encoders.is_empty() {
                ptr::null()
            } else {
                self.encoders.as_ptr()
            },
            encoder_count: self.encoders.len() as u32,
        }
    }
    pub fn xml(&self) -> NvC2Bytes {
        bytes(&self.xml)
    }
}
pub fn bytes(s: &CString) -> NvC2Bytes {
    NvC2Bytes {
        data: s.as_ptr(),
        len: s.as_bytes().len(),
    }
}
pub fn no_decoder_reason(gpu: &str, nvdec_class: u32) -> String {
    if nvdec_class == 0 {
        format!("hardware video decode: not available on {gpu} (no NVDEC class this decoder supports; supported from Turing): Android software decoders are used")
    } else {
        format!("hardware video decode: not available on {gpu} (NVDEC class 0x{nvdec_class:x}: no supported decode codecs): Android software decoders are used")
    }
}
pub fn no_decoder_xml(gpu: &str, nvdec_class: u32) -> String {
    let mut reason = no_decoder_reason(gpu, nvdec_class);
    while reason.contains("--") {
        reason = reason.replace("--", "-");
    }
    format!("<?xml version=\"1.0\" encoding=\"utf-8\" ?>\n<!-- Generated by nvc2-xmlgen from nv_video_device_open() on this GPU: no hardware decoders.\n     {reason}.\n     Do not edit: regenerate (the service checks this file against the GPU at every start). -->\n<MediaCodecs>\n    <Decoders>\n    </Decoders>\n</MediaCodecs>\n")
}

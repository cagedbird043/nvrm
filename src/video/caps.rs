#[cfg(test)]
mod tests {
    use super::*;
    fn caps(codec: u32) -> Result<NvVideoCaps, Error> {
        Ok(NvVideoCaps {
            codec,
            supported: if codec == CODEC_AV1 { 0 } else { 1 },
            min_width: 33,
            min_height: 17,
            max_width: if codec == CODEC_H264 { 4096 } else { 8192 },
            max_height: 8192,
            bit_depth_mask: 1 << 8,
            ..Default::default()
        })
    }
    #[test]
    fn xml_policy_and_immutable_views() {
        let c = NvC2Caps::query(caps, || Ok(0xc9b7)).unwrap();
        let v = c.view();
        assert_eq!(
            (v.decoder_count, v.encoder_count, v.nvenc_class),
            (3, 3, 0xc9b7)
        );
        let x = c.xml.to_str().unwrap();
        assert!(!x.contains("av1.decoder"));
        assert!(x.contains("min=\"34x18\" max=\"8192x8192\""));
        assert!(x.contains("max=\"4096x8192\""));
        assert!(x.contains("min=\"50x2\" max=\"4096x4096\""));
        assert!(x.contains("av1.encoder\" type=\"video/av01\""));
        assert!(x.find("<Encoders>").unwrap() > x.find("</Decoders>").unwrap());
        let other = NvC2Caps::query(caps, || Ok(0xc4b7)).unwrap();
        assert_eq!(other.view().encoder_count, 0);
        assert!(other.view().encoders.is_null());
        assert!(!other.xml.to_str().unwrap().contains("encoder"));
        assert_eq!(v.decoders, c.view().decoders);
        assert_eq!(c.xml().data, c.xml().data);
    }
    #[test]
    fn errors_are_atomic() {
        let empty = NvC2Caps::query(
            |_| Ok(NvVideoCaps::default()),
            || panic!("must not open encoder"),
        ).unwrap();
        let view = empty.view();
        assert_eq!(view.decoder_count, 0);
        assert_eq!(view.encoder_count, 0);
        assert_eq!(view.nvenc_class, 0);
        assert!(view.decoders.is_null() && view.encoders.is_null());
        assert!(NvC2Caps::query(
            |codec| {
                let mut c = caps(codec)?;
                c.supported = 1;
                c.bit_depth_mask = 0;
                Ok(c)
            },
            || Ok(0xc9b7)
        )
        .err()
        .unwrap()
        .1
        .contains("unusable"));
        assert_eq!(
            NvC2Caps::query(caps, || Err((-5, "nv_venc_open failed".into())))
                .err()
                .unwrap()
                .0,
            -5
        );
        assert_eq!(
            NvC2Caps::query(|_| Err((-4, "allocation".into())), || Ok(0))
                .err()
                .unwrap()
                .0,
            -4
        );
    }
    #[test]
    fn no_decoder_contract() {
        let reason = no_decoder_reason("stub", 0);
        assert_eq!(reason,"hardware video decode: not available on stub (no NVDEC class this decoder supports; supported from Turing): Android software decoders are used");
        let xml = no_decoder_xml("a---b", 0);
        assert!(xml.contains("on a-b ("));
        assert!(!xml.contains("<MediaCodec "));
        assert!(xml.ends_with("</MediaCodecs>\n"));
        let known = no_decoder_xml("a---b", 0xc3b0);
        assert_ne!(known, xml);
        assert!(known.contains("NVDEC class 0xc3b0: no supported decode codecs"));
        assert!(!known.contains("<MediaCodec "));
        for invalid in [0, 1, 2] {
            assert!(NvC2Caps::query(|codec| {
                let mut c = caps(codec)?;
                match invalid {
                    0 => c.max_width = 0,
                    1 => c.min_height = c.max_height + 1,
                    _ => c.bit_depth_mask = 0,
                }
                Ok(c)
            }, || panic!("must not open encoder")).is_err());
        }
    }
}

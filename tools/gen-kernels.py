#!/usr/bin/env python3
"""Generate the precompiled compute kernels of the video engine (src/video/compute.rs).

  --spirv   compile shaders/<name>.comp to shaders/<name>.spv with glslangValidator (host)
  (default) compile every shaders/<name>.spv for every shader model with the Mesa NAK generator
            (compiler/gen.c, built by `compiler/build.py --target host`) and write
            shaders/sm<sm>/<name>.bin and src/video/kernels.rs
  --check   regenerate into memory and fail unless the committed files are byte-identical

The generator runs where build/nak-host was built (localhost/nvk-native-a17, repository at /work).
The runtime carries no compiler: it loads the SASS, copies the QMD template and ORs the per-launch
program address, cbuf 0 address and grid size into the generated bit runs.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

NATIVE = Path(__file__).resolve().parents[1]
ROOT = NATIVE.parents[2]
GEN = ROOT / "build/nak-host/src/nouveau/native-bridge/nv-nak-gen"
MESA_PIN = "ddaf85e353442d9d7f192fdcf1823e652e3f2ee3"  # compiler/build.py PIN (mesa-26.2.5)
SHADERS = NATIVE / "shaders"
OUT_RS = NATIVE / "src/video/kernels.rs"
# Shader models with generated kernels. Runtime use is further limited to the compute classes in
# compute.rs VALIDATED_CLASSES (hardware-tested); the rest only have unit-tested QMD packing.
SMS = (75, 80, 86, 89, 90, 120)
# (name, test-only): test kernels exist for the hardware tests of the engine itself.
KERNELS = (("bgra_nv12", False), ("vpp", False), ("fill", True), ("mix", True))
VARIABLES = ("program", "cbuf", "grid_x", "grid_y", "grid_z")
ABI = 1


def spirv():
    for name, _ in KERNELS:
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.2", "-o",
                        str(SHADERS / f"{name}.spv"), str(SHADERS / f"{name}.comp")], check=True)


def generate():
    """{path: bytes} of every generated file."""
    files = {}
    entries, samples = [], []
    for sm in SMS:
        for name, test in KERNELS:
            out = subprocess.run([str(GEN), str(sm), "main", str(SHADERS / f"{name}.spv")],
                                 check=True, capture_output=True, text=True).stdout
            k = json.loads(out)
            code = bytes.fromhex(k["code"])
            files[SHADERS / f"sm{sm}/{name}.bin"] = code
            runs = ", ".join("&[" + ", ".join(f"({a}, {b}, {c})" for a, b, c in k["runs"][v]) + "]"
                             for v in VARIABLES)
            entry = (f"    Kernel {{\n"
                     f"        name: \"{name}\",\n"
                     f"        sm: {sm},\n"
                     f"        compute_class: {k['compute_class']:#06x},\n"
                     f"        code: include_bytes!(\"../../shaders/sm{sm}/{name}.bin\"),\n"
                     f"        registers: {k['registers']},\n"
                     f"        shared_bytes: {k['shared_bytes']},\n"
                     f"        barriers: {k['barriers']},\n"
                     f"        workgroup: {k['workgroup']},\n"
                     f"        cbuf_bytes: {k['cbuf_bytes']},\n"
                     f"        qmd: &{k['qmd']},\n"
                     f"        runs: [{runs}],\n"
                     f"    }},\n")
            entries.append((test, entry))
            for s in k["samples"]:
                samples.append(f"    (\"{name}\", {sm}, {s['values']}, &{s['qmd']}),\n")
    rs = ["// @generated by tools/gen-kernels.py from shaders/*.spv with Mesa NAK "
          f"{MESA_PIN}; do not edit.\n",
          "// Regenerate after changing a shader, the bridge (compiler/) or the Mesa pin, and check with\n",
          "// `tools/gen-kernels.py --check`.\n",
          "use super::compute::Kernel;\n\n",
          f"/// Version of the kernel contract (bindings, cbuf layout, runs) these tables follow.\n",
          f"pub(crate) const ABI: u32 = {ABI};\n\n",
          "/// Production kernels, every shader model.\n",
          "pub(crate) static KERNELS: &[Kernel] = &[\n"]
    rs += [e for test, e in entries if not test]
    rs += ["];\n\n", "/// Kernels for the engine's own hardware tests.\n", "#[cfg(test)]\n",
           "pub(crate) static TEST_KERNELS: &[Kernel] = &[\n"]
    rs += [e for test, e in entries if test]
    rs += ["];\n\n",
           "/// nak_fill_qmd results for combined launch values (program, cbuf, grid x/y/z): the\n",
           "/// runtime packing must reproduce them bit for bit.\n",
           "#[cfg(test)]\n",
           "pub(crate) static QMD_SAMPLES: &[(&str, u32, [u64; 5], &[u32])] = &[\n"]
    rs += samples
    rs += ["];\n"]
    files[OUT_RS] = "".join(rs).encode()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spirv", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.spirv:
        spirv()
        return
    files = generate()
    if args.check:
        stale = [p for p, data in files.items() if not p.exists() or p.read_bytes() != data]
        expected = {p for p in files if p.suffix == ".bin"}
        extra = [p for p in SHADERS.glob("sm*/*.bin") if p not in expected]
        for p in stale + extra:
            print(f"gen-kernels: {p.relative_to(NATIVE)} is not what the generator produces", file=sys.stderr)
        sys.exit(1 if stale or extra else 0)
    for p, data in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    print(f"gen-kernels: {len(files) - 1} kernels, {OUT_RS.relative_to(NATIVE)}")


if __name__ == "__main__":
    main()
